// Brand icon generator (icon "6a" from the Sroka Icons v2 design: black bookmark-magpie, blue band,
// yellow beak, white tile). One source, every platform. Output is committed; rerun only when the mark changes.
//
//   npm i sharp --prefix /tmp/sharp && SHARP_PREFIX=/tmp/sharp node scripts/make-icons.mjs
//
// sharp is deliberately not a dependency; SHARP_PREFIX points at any directory where it is installed.
import { mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const sharp = createRequire(join(process.env.SHARP_PREFIX ?? process.cwd(), "noop.js"))("sharp");
const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const COLORS = { tile: "#ffffff", ink: "#15171c", band: "#1e6f8f", beak: "#f2c84b" };
// Shapes in a 100×100 tile. The band sits fully inside the body, so no clip is needed.
const BODY = "M30 20 H62 Q70 20 70 28 V82 L50 77 L30 82 Z";
const BAND = "30,56 70,46 70,58 30,68";
const BEAK = "69,27 83,33 69,39";
const bird = `<path d="${BODY}" fill="${COLORS.ink}"/><polygon points="${BAND}" fill="${COLORS.band}"/><polygon points="${BEAK}" fill="${COLORS.beak}"/><circle cx="58" cy="32" r="4" fill="${COLORS.tile}"/>`;

/** shape: "square" (full bleed; for OS-masked icons), "rounded" (baked corners), "circle". */
const svg = (shape = "square") => {
  const tile =
    shape === "circle" ? `<circle cx="50" cy="50" r="50" fill="${COLORS.tile}"/>`
    : `<rect width="100" height="100"${shape === "rounded" ? ' rx="22"' : ""} fill="${COLORS.tile}"/>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">${tile}${bird}</svg>\n`;
};
// Single-colour glyph (body with band + eye cut out), for monochrome contexts.
const glyphPath = `${BODY} M30 56 L70 46 L70 58 L30 68 Z M54 32 a4 4 0 1 0 8 0 a4 4 0 1 0 -8 0 Z`;
const glyphSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="26 16 60 70"><path fill-rule="evenodd" d="${glyphPath}" fill="${COLORS.ink}"/><polygon points="${BEAK}" fill="${COLORS.beak}"/></svg>\n`;

const write = (rel, data) => {
  const p = join(root, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, data);
};
const png = (s, size, rel) => sharp(Buffer.from(s), { density: 72 * Math.ceil(size / 100) * 4 }).resize(size, size).png().toFile(join(root, rel));
const webp = (s, size, rel) => sharp(Buffer.from(s), { density: 72 * Math.ceil(size / 100) * 4 }).resize(size, size).webp({ lossless: true }).toFile(join(root, rel));

// Canonical sources (README, docs).
write("docs/brand/icon.svg", svg("square"));
write("docs/brand/icon-rounded.svg", svg("rounded"));
write("docs/brand/glyph.svg", glyphSvg);

// Web: favicon + touch icon (served from apps/web/public → dist root).
write("apps/web/public/icon.svg", svg("rounded"));
await png(svg("rounded"), 32, "apps/web/public/favicon-32.png");
await png(svg("square"), 180, "apps/web/public/apple-touch-icon.png");
// PWA install icons (apps/web/public/manifest.webmanifest).
for (const n of [192, 512]) await png(svg("rounded"), n, `apps/web/public/icon-${n}.png`);

// Chrome extension: Chrome does not mask icons, so corners are baked in.
write("apps/extension/assets/icon.svg", svg("rounded"));
for (const n of [16, 32, 48, 128]) await png(svg("rounded"), n, `apps/extension/public/icon/${n}.png`);

// Android: legacy mipmaps (pre-26), Play Store, adaptive layers.
const res = "apps/android/app/src/main/res";
for (const [d, n] of [["mdpi", 48], ["hdpi", 72], ["xhdpi", 96], ["xxhdpi", 144], ["xxxhdpi", 192]]) {
  await webp(svg("rounded"), n, `${res}/mipmap-${d}/ic_launcher.webp`);
  await webp(svg("circle"), n, `${res}/mipmap-${d}/ic_launcher_round.webp`);
}
await png(svg("square"), 512, "apps/android/app/src/main/ic_launcher-playstore.png");

// Adaptive foreground: the 100-unit tile maps onto the 72dp visible area of the 108dp layer.
const group = (body) => `    <group android:scaleX="0.72" android:scaleY="0.72" android:translateX="18" android:translateY="18">\n${body}    </group>\n`;
const vector = (body) =>
  `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/make-icons.mjs; do not edit. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="108dp"\n    android:height="108dp"\n    android:viewportWidth="108"\n    android:viewportHeight="108">\n${group(body)}</vector>\n`;
const pts = (p) => `M${p.replace(/ /g, " L")} Z`;
const circle = "M54,32 a4,4 0 1,0 8,0 a4,4 0 1,0 -8,0 Z";
write(
  `${res}/drawable/ic_launcher_foreground.xml`,
  vector(
    [
      [BODY, COLORS.ink],
      [pts(BAND), COLORS.band],
      [pts(BEAK), COLORS.beak],
      [circle, COLORS.tile],
    ]
      .map(([d, c]) => `        <path android:fillColor="${c.toUpperCase()}" android:pathData="${d}" />\n`)
      .join(""),
  ),
);
// Themed (Android 13+) icon: the system tints this single-colour layer.
write(
  `${res}/drawable/ic_launcher_monochrome.xml`,
  vector(
    `        <path android:fillColor="#FF000000" android:fillType="evenOdd" android:pathData="${BODY} ${pts(BAND)} ${circle}" />\n` +
      `        <path android:fillColor="#FF000000" android:pathData="${pts(BEAK)}" />\n`,
  ),
);
write(
  `${res}/drawable/ic_launcher_background.xml`,
  `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/make-icons.mjs; do not edit. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="108dp"\n    android:height="108dp"\n    android:viewportWidth="108"\n    android:viewportHeight="108">\n    <path android:fillColor="#FFFFFFFF" android:pathData="M0,0h108v108h-108z" />\n</vector>\n`,
);
const adaptive = `<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n    <background android:drawable="@drawable/ic_launcher_background" />\n    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n</adaptive-icon>\n`;
write(`${res}/mipmap-anydpi-v26/ic_launcher.xml`, adaptive);
write(`${res}/mipmap-anydpi-v26/ic_launcher_round.xml`, adaptive);

console.log("icons written");
