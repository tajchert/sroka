#!/usr/bin/env node
// `npm run dev -w @sroka/api`: local stack = sroka-api + sroka-parser in ONE `wrangler dev` (shared local D1/R2/KV/DO
// state under workers/api/.wrangler/state, queue producer → consumer wired in-process).
//
// Why a generated config: wrangler.jsonc has production `routes` (custom domains). When a config has routes,
// `wrangler dev` infers an upstream host from the first route and rewrites every request URL to http://sroka.app/…
// AND rewrites the Origin/Referer headers that mention localhost:8787 to http://sroka.app. That breaks Better Auth's
// trustedOrigins check (403 INVALID_ORIGIN) and the content-host branching (127.0.0.1:8787 would be seen as sroka.app).
// So we write wrangler.dev.jsonc (gitignored) = wrangler.jsonc minus `routes`, next to it so relative paths
// (main, assets, migrations, .wrangler/state) resolve identically, and run wrangler dev on that.
//
// Extra CLI args are passed through to wrangler (e.g. `npm run dev -w @sroka/api -- --port 8788`).
import { spawn } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Strip // and block comments plus trailing commas from JSONC (string-aware). */
export function parseJsonc(text) {
  let out = "";
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (ch === '"') {
      let j = i + 1;
      while (j < text.length && text[j] !== '"') j += text[j] === "\\" ? 2 : 1;
      out += text.slice(i, j + 1);
      i = j;
    } else if (ch === "/" && text[i + 1] === "/") {
      while (i < text.length && text[i] !== "\n") i++;
      out += "\n";
    } else if (ch === "/" && text[i + 1] === "*") {
      i = text.indexOf("*/", i + 2) + 1;
    } else out += ch;
  }
  return JSON.parse(out.replace(/,(\s*[}\]])/g, "$1"));
}

const config = parseJsonc(readFileSync(join(dir, "wrangler.jsonc"), "utf8"));
delete config.routes;
config.$schema = "../../node_modules/wrangler/config-schema.json";
writeFileSync(
  join(dir, "wrangler.dev.jsonc"),
  `// GENERATED by scripts/dev.mjs from wrangler.jsonc (routes removed for local dev). Do not edit.\n${JSON.stringify(config, null, 2)}\n`,
);

if (!existsSync(join(dir, ".dev.vars"))) {
  console.error("[sroka] workers/api/.dev.vars missing — run `node scripts/dev-setup.mjs` from the repo root first.");
  process.exit(1);
}

const args = ["wrangler", "dev", "-c", "wrangler.dev.jsonc", "-c", "../parser/wrangler.jsonc", ...process.argv.slice(2)];
const child = spawn("npx", args, { cwd: dir, stdio: "inherit" });
for (const sig of ["SIGINT", "SIGTERM"]) process.on(sig, () => child.kill(sig));
child.on("exit", (code, signal) => process.exit(code ?? (signal ? 1 : 0)));
